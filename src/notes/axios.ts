/*
Axios interceptors are special functions that let you intercept HTTP requests and responses before they are sent or handled

Request Interceptors
Request Interceptors: Run before your app sends an HTTP request. Use them to add authorization tokens, change headers, or log outgoing data

Response Interceptors
Response Interceptors: Run after the server replies but before your code receives the data. Use them to handle global errors like 401 Unauthorized, format data, or log responses
*/